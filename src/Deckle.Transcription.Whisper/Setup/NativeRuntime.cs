using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.IO.Compression;
using System.Threading;
using System.Threading.Tasks;

using Deckle.Core;
namespace Deckle.Transcription.Whisper;

// Single source of truth for the whisper.cpp native runtime catalog: the
// Visual C++ runtime, the ggml core, the ggml backends and whisper.dll.
// Anything that detects, installs, copies or loads these files goes through
// this class, with no parallel catalog.
//
// scripts/lib/native-runtime-release.psm1 parses EntryDll, RequiredDllNames and
// CurrentBundle out of this file's text with regexes, so keep the shape of
// those three declarations.
//
// The Whisper model catalog lives in SpeechModels: different lifecycle,
// different trust boundary (downloaded from HuggingFace vs redistributed
// through our own release).
public static class NativeRuntime
{
    // Must match WhisperPInvoke.EntryDll, the file the resolver loads.
    public const string EntryDll = "whisper.dll";

    // In load order: a DLL only imports names above it. The runtime is the
    // Visual C++ Redistributable of the toolset that built whisper.cpp,
    // shipped beside it because a bare Windows has no C++ runtime of its own
    // (msvcp140, vcruntime140, vcruntime140_1) and because OpenMP (vcomp140)
    // never ships with Windows. The ggml-cpu-* variants are one CPU backend
    // compiled per instruction set; ggml picks the best one this CPU runs.
    // ggml-vulkan.dll is the GPU backend; it needs the Vulkan loader the
    // graphics driver installs, the one import the bundle leaves to the
    // machine. The backends are not imported by anyone: ggml loads them
    // itself from this folder (NativeRuntimeLoader).
    public static IReadOnlyList<string> RequiredDllNames { get; } = new[]
    {
        "vcruntime140.dll",
        "vcruntime140_1.dll",
        "msvcp140.dll",
        "vcomp140.dll",
        "ggml-base.dll",
        "ggml.dll",
        "ggml-cpu-x64.dll",
        "ggml-cpu-sse42.dll",
        "ggml-cpu-sandybridge.dll",
        "ggml-cpu-haswell.dll",
        "ggml-cpu-skylakex.dll",
        "ggml-cpu-cannonlake.dll",
        "ggml-cpu-cascadelake.dll",
        "ggml-cpu-icelake.dll",
        "ggml-cpu-alderlake.dll",
        "ggml-vulkan.dll",
        EntryDll,
    };

    // A backend is loaded by ggml at runtime, never imported: it may fail to
    // load on a given machine without taking the runtime down.
    public static bool IsBackendDll(string name) =>
        name.StartsWith("ggml-", StringComparison.OrdinalIgnoreCase) &&
        !name.Equals("ggml-base.dll", StringComparison.OrdinalIgnoreCase);

    // The Vulkan backend imports vulkan-1.dll, installed by the graphics
    // driver, not by Deckle: scripts/lib/native-runtime-release.psm1 declares
    // that name external when it checks a bundle's imports. It is the one
    // catalog DLL allowed not to load on a machine.
    public static bool IsVulkanBackend(string name) =>
        name.Equals("ggml-vulkan.dll", StringComparison.OrdinalIgnoreCase);

    // Regenerated by scripts/commands/release/publish-native-runtime.ps1, which
    // prints a paste-ready CurrentBundle. The SHA256 changes on every rebuild
    // (zip timestamps), so update it together with the URL and SizeBytes after
    // every publish.
    public sealed record NativeRuntimeBundle(
        string Version,
        string Url,
        string Sha256,
        long SizeBytes,
        string DisplayName);

    public static NativeRuntimeBundle CurrentBundle { get; } = new(
        Version:     "1.9.2",
        Url:         "https://github.com/louisfifre/deckle/releases/download/native-v1.9.2/deckle-native-1.9.2.zip",
        Sha256:      "40cb8007d4795133db8c99fe04e1e4ec91e2f04b205b557eb23b477dc1a1bf20",
        SizeBytes:   26_282_437L,
        DisplayName: "Whisper.cpp + Vulkan runtime");

    // While the URL is a placeholder, auto-download is disabled and the wizard
    // falls back to Browse... instead of failing at its first run.
    public static bool BundleUrlIsPlaceholder =>
        CurrentBundle.Url.Contains("PLACEHOLDER", StringComparison.OrdinalIgnoreCase);

    // True only when the complete native catalog is present. whisper.dll
    // alone is not an installation: Windows still needs the ggml core, the
    // backends and the C++ runtime beside it. Keeping this gate strict makes a
    // partial manual import or interrupted extraction repairable by the setup
    // wizard instead of deferring the failure to the first transcription.
    //
    // Presence is not loadability: a file can be there and still not load
    // here (wrong architecture, an import this machine lacks). CheckLoad
    // answers that second question.
    public static bool IsInstalled() =>
        IsInstalled(AppPaths.NativeDirectory);

    internal static bool IsInstalled(string nativeDirectory) =>
        GetMissing(nativeDirectory).Count == 0;

    // Loads the installed catalog the way the first transcription will, with
    // the search limited to the native folder and System32, and reports the
    // first DLL that does not load and the import it misses. Provisioning
    // runs it after extraction and the app at startup, so that "installed"
    // means "loads on this machine".
    public static NativeRuntimeLoadCheck CheckLoad()
    {
        NativeRuntimeLoadCheck check = CheckLoad(AppPaths.NativeDirectory);
        s_lastCheck = check;
        return check;
    }

    internal static NativeRuntimeLoadCheck CheckLoad(string nativeDirectory) =>
        NativeRuntimeLoader.Check(nativeDirectory);

    // The last answer of CheckLoad for the app's native folder. The wizard
    // asks IsUsable from every estimate it refreshes, and each check loads
    // the whole catalog; the files only change through the provisioning
    // below, which drops the answer. A folder edited by hand while the app
    // runs keeps the old answer until the next provisioning or restart.
    private static NativeRuntimeLoadCheck? s_lastCheck;

    // The question the install plan and the Settings page ask: the catalog
    // is complete and loads here. The Vulkan backend may fail (CheckLoad
    // allows it) without making the runtime unusable.
    public static bool IsUsable() =>
        IsInstalled() && (s_lastCheck ?? CheckLoad()).Loads;

    // Only catalog DLLs are copied, so pointing at a build folder full of other
    // artifacts keeps NativeDirectory tidy. A complete copy is load-checked at
    // once: a runtime picked by hand is the one most likely to miss an import.
    public static int CopyFromFolder(string sourcePath)
    {
        int copied = CopyFromFolder(sourcePath, AppPaths.NativeDirectory);
        s_lastCheck = null;
        if (IsInstalled()) CheckLoad();
        return copied;
    }

    internal static int CopyFromFolder(string sourcePath, string nativeDirectory)
    {
        Directory.CreateDirectory(nativeDirectory);
        int copied = 0;
        foreach (string name in RequiredDllNames)
        {
            string from = Path.Combine(sourcePath, name);
            if (!File.Exists(from)) continue;
            string to = Path.Combine(nativeDirectory, name);
            File.Copy(from, to, overwrite: true);
            copied++;
        }

        IReadOnlyList<string> missing = GetMissing(nativeDirectory);
        DeckleWhisperSource.Log.NativeRuntimeCopied(copied, missing.Count);
        DeckleWhisperSource.Log.NativeRuntimeCopiedDetail(sourcePath, string.Join(",", missing));
        return copied;
    }

    // Two safety properties:
    //
    //   1. Catalog filter — only entries whose name matches RequiredDllNames
    //      are extracted. Any other entry in the zip (PROVENANCE.txt,
    //      SHA256SUMS, hypothetical malicious filename, path traversal
    //      attempt) is ignored. The catalog is the trust boundary.
    //
    //   2. Atomic publish per file — each DLL is extracted to <name>.partial,
    //      then File.Move(..., overwrite: true) renames it to its final
    //      name. An interrupted extract leaves a .partial the next attempt
    //      overwrites; the final filename never appears half-written under
    //      a process that may already be loading it.
    public static async Task<int> InstallFromZipAsync(
        string zipPath,
        CancellationToken ct)
    {
        s_lastCheck = null;
        return await InstallFromZipAsync(zipPath, AppPaths.NativeDirectory, ct).ConfigureAwait(false);
    }

    internal static async Task<int> InstallFromZipAsync(
        string zipPath,
        string nativeDirectory,
        CancellationToken ct)
    {
        Directory.CreateDirectory(nativeDirectory);

        using var archive = ZipFile.OpenRead(zipPath);
        int extracted = 0;

        foreach (string name in RequiredDllNames)
        {
            ct.ThrowIfCancellationRequested();

            ZipArchiveEntry? entry = archive.GetEntry(name);
            if (entry is null) continue;

            string finalPath   = Path.Combine(nativeDirectory, name);
            string partialPath = finalPath + ".partial";

            try
            {
                using (Stream src = entry.Open())
                using (var dst = new FileStream(
                    partialPath,
                    FileMode.Create, FileAccess.Write, FileShare.None,
                    bufferSize: 81920, useAsync: true))
                {
                    await src.CopyToAsync(dst, ct).ConfigureAwait(false);
                }
                File.Move(partialPath, finalPath, overwrite: true);
                extracted++;
            }
            catch
            {
                DeletePartial(partialPath);
                throw;
            }
        }

        return extracted;
    }

    private static void DeletePartial(string path)
    {
        try { if (File.Exists(path)) File.Delete(path); }
        catch (Exception ex)
        {
            // The next attempt overwrites the leftover, so the user gets the
            // same result either way.
            DeckleWhisperSource.Log.NativeRuntimeCleanupFailed(path, ex.GetType().Name, ex.Message);
        }
    }

    public static async Task<ProvisioningResult> ProvisionAsync(
        IProgress<Downloader.DownloadProgress> progress,
        CancellationToken ct)
    {
        string version = CurrentBundle.Version;
        DeckleWhisperSource.Log.NativeRuntimeProvisionStarted(version);

        if (BundleUrlIsPlaceholder)
        {
            DeckleWhisperSource.Log.NativeRuntimeProvisionFailed("placeholder_url", version, "", "");
            DeckleWhisperSource.Log.NativeRuntimeProvisionFailedDetail(CurrentBundle.Url, 0, "", 0);
            return ProvisioningResult.Fail(
                "auto-download URL is a placeholder; use Browse... on the previous step");
        }

        var sw = Stopwatch.StartNew();
        // The single end event is written in the finally below, from these, so
        // every exit path (failed result, cancellation, exception) closes the
        // start above exactly once.
        string outcome = "failed";
        string reason = "exception";
        string exType = "";
        string exMessage = "";
        int extracted = 0;

        Directory.CreateDirectory(AppPaths.NativeDirectory);
        string zipPath = Path.Combine(AppPaths.NativeDirectory, "_bundle.zip");
        try
        {
            Downloader.DownloadResult download = await Downloader.DownloadAsync(
                CurrentBundle.Url, zipPath, CurrentBundle.Sha256, progress, ct);
            if (!download.Success)
            {
                reason = "download_failed";
                exMessage = download.ErrorMessage ?? "download failed";
                return ProvisioningResult.Fail(download.ErrorMessage ?? "download failed");
            }

            extracted = await InstallFromZipAsync(zipPath, ct);
            if (extracted < RequiredDllNames.Count)
            {
                reason = "bundle_incomplete";
                return ProvisioningResult.Fail(
                    $"bundle is incomplete (extracted {extracted}/{RequiredDllNames.Count} DLLs)");
            }

            // A bundle that is all there can still not load here (an import
            // this machine lacks, a file that is not a 64-bit DLL): the
            // person learns it now, in the wizard, not at the first take.
            NativeRuntimeLoadCheck check = CheckLoad();
            if (!check.Loads)
            {
                reason = "load_check_failed";
                exMessage = check.FirstFailure?.Summary ?? "no CPU backend loaded";
                return ProvisioningResult.Fail(exMessage);
            }

            outcome = "completed";
            return ProvisioningResult.Ok(CurrentBundle.SizeBytes, download.ActualSha256);
        }
        catch (OperationCanceledException)
        {
            outcome = "cancelled";
            throw;
        }
        catch (Exception ex)
        {
            exType = ex.GetType().Name;
            exMessage = ex.Message;
            throw;
        }
        finally
        {
            DeletePartial(zipPath);

            sw.Stop();
            if (outcome == "failed")
            {
                DeckleWhisperSource.Log.NativeRuntimeProvisionFailed(reason, version, exType, exMessage);
                DeckleWhisperSource.Log.NativeRuntimeProvisionFailedDetail(
                    CurrentBundle.Url, extracted, string.Join(",", GetMissing()), sw.ElapsedMilliseconds);
            }
            else
            {
                DeckleWhisperSource.Log.NativeRuntimeProvisionEnded(version, outcome, extracted, sw.ElapsedMilliseconds);
            }
        }
    }

    public static IReadOnlyList<string> GetMissing()
        => GetMissing(AppPaths.NativeDirectory);

    internal static IReadOnlyList<string> GetMissing(string nativeDirectory)
    {
        var missing = new List<string>();
        foreach (string name in RequiredDllNames)
        {
            string path = Path.Combine(nativeDirectory, name);
            if (!File.Exists(path)) missing.Add(name);
        }
        return missing;
    }
}
